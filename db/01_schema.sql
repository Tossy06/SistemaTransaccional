CREATE TABLE "acta_aprobacion" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "acta_id" integer,
  "usuario_id" integer,
  "rol_en_aprobacion" varchar,
