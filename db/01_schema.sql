-- ======================= TABLAS =======================================
CREATE TABLE "asamblea" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "conjunto_id" integer,
  "tipo" varchar,
  "fecha" date,
  "hora" time,
  "lugar_modalidad" varchar,
  "orden_del_dia_cerrado" boolean DEFAULT false,
  "estado" varchar,
  "requiere_segunda_convocatoria" boolean DEFAULT false,
  "asamblea_original_id" integer,
  "quorum_alcanzado" decimal,
  "fecha_creacion" timestamp DEFAULT (now()),
  "modalidad" varchar DEFAULT 'virtual',
  "enlace_videollamada" varchar
);

CREATE TABLE "conjunto" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar,
  "nit" varchar UNIQUE,
  "direccion" varchar,
  "ciudad" varchar,
  "numero_unidades" integer,
  "coeficiente_total" decimal DEFAULT 100,
  "fecha_registro" timestamp DEFAULT (now()),
  "activo" boolean DEFAULT true,
  "formulario_token" varchar UNIQUE
);

CREATE TABLE "unidad" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "conjunto_id" integer,
  "identificador" varchar,
  "propietario_nombre" varchar,
  "propietario_documento" varchar,
  "propietario_email" varchar,
  "propietario_telefono" varchar,
  "coeficiente_copropiedad" decimal,
  "activo" boolean DEFAULT true
);

CREATE TABLE "usuario" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar,
  "email" varchar UNIQUE,
  "password_hash" varchar,
  "documento" varchar UNIQUE,
  "telefono" varchar,
  "activo" boolean DEFAULT true,
  "fecha_creacion" timestamp DEFAULT (now())
);

CREATE TABLE "rol" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar UNIQUE,
  "descripcion" varchar,
  "activo" boolean DEFAULT true
);

CREATE TABLE "usuario_rol" (
  "usuario_id" integer,
  "rol_id" integer,
  "fecha_asignacion" timestamp DEFAULT (now()),
  PRIMARY KEY ("usuario_id", "rol_id")
);

CREATE TABLE "convocatoria" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "asamblea_id" integer,
  "unidad_id" integer,
  "fecha_envio" timestamp DEFAULT (now()),
  "medio" varchar,
  "confirmado_entrega" boolean DEFAULT false,
  "token_acceso" varchar UNIQUE
);

CREATE TABLE "poder" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "asamblea_id" integer,
  "unidad_id" integer,
  "apoderado_nombre" varchar,
  "apoderado_documento" varchar,
  "fecha_registro" timestamp DEFAULT (now()),
  "vigente" boolean DEFAULT true
);

CREATE TABLE "asistencia" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "asamblea_id" integer,
  "unidad_id" integer,
  "poder_id" integer,
  "tipo_asistencia" varchar,
  "hora_registro" timestamp DEFAULT (now()),
  "coeficiente_al_momento" decimal
);

CREATE TABLE "punto_orden_dia" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "asamblea_id" integer,
  "orden" integer,
  "descripcion" varchar,
  "tipo_mayoria" varchar,
  "estado" varchar,
  "fecha_apertura" timestamp,
  "fecha_cierre" timestamp
);

CREATE TABLE "voto" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "punto_id" integer,
  "unidad_id" integer,
  "usuario_id" integer,
  "decision" varchar,
  "coeficiente_al_momento" decimal,
  "fecha_voto" timestamp DEFAULT (now())
);

CREATE TABLE "resultado_votacion" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "punto_id" integer,
  "total_a_favor" decimal,
  "total_en_contra" decimal,
  "total_abstencion" decimal,
  "resultado" varchar,
  "fecha_calculo" timestamp DEFAULT (now())
);

CREATE TABLE "acta" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "asamblea_id" integer,
  "contenido" text,
  "hash" varchar,
  "estado" varchar,
  "fecha_generacion" timestamp DEFAULT (now())
