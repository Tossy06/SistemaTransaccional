-- Dominios de los campos tipo "varchar" del modelo
-- Modalidad (art. 42, Ley 675: reuniones no presenciales); la sala virtual exige enlace https
ALTER TABLE "asamblea" ADD CONSTRAINT ck_asamblea_modalidad
  CHECK (modalidad IN ('presencial', 'virtual', 'mixta'));
ALTER TABLE "asamblea" ADD CONSTRAINT ck_asamblea_enlace
  CHECK (enlace_videollamada IS NULL OR enlace_videollamada LIKE 'https://%');
ALTER TABLE "asamblea" ADD CONSTRAINT ck_asamblea_tipo
  CHECK (tipo IN ('ordinaria', 'extraordinaria'));
ALTER TABLE "asamblea" ADD CONSTRAINT ck_asamblea_estado
  CHECK (estado IN ('programada', 'convocada', 'en_curso', 'sin_quorum', 'finalizada'));
ALTER TABLE "asamblea" ALTER COLUMN estado SET DEFAULT 'programada';
ALTER TABLE "asamblea" ADD CONSTRAINT ck_asamblea_quorum
  CHECK (quorum_alcanzado IS NULL OR quorum_alcanzado BETWEEN 0 AND 100);

ALTER TABLE "unidad" ADD CONSTRAINT ck_unidad_coeficiente
  CHECK (coeficiente_copropiedad > 0);
CREATE UNIQUE INDEX uq_unidad_identificador ON "unidad" ("conjunto_id", "identificador");

ALTER TABLE "convocatoria" ADD CONSTRAINT ck_convocatoria_medio
  CHECK (medio IN ('email', 'fisico', 'whatsapp'));
CREATE UNIQUE INDEX uq_convocatoria_unidad ON "convocatoria" ("asamblea_id", "unidad_id");

ALTER TABLE "asistencia" ADD CONSTRAINT ck_asistencia_tipo
  CHECK (tipo_asistencia IN ('presencial', 'virtual', 'poder'));
ALTER TABLE "asistencia" ADD CONSTRAINT ck_asistencia_poder
  CHECK ((tipo_asistencia = 'poder') = (poder_id IS NOT NULL));

ALTER TABLE "punto_orden_dia" ADD CONSTRAINT ck_punto_mayoria
  CHECK (tipo_mayoria IN ('simple', 'calificada_70'));
ALTER TABLE "punto_orden_dia" ADD CONSTRAINT ck_punto_estado
  CHECK (estado IN ('pendiente', 'abierto', 'cerrado'));
ALTER TABLE "punto_orden_dia" ALTER COLUMN estado SET DEFAULT 'pendiente';
CREATE UNIQUE INDEX uq_punto_orden ON "punto_orden_dia" ("asamblea_id", "orden");
-- Un solo punto en votación a la vez por asamblea (RF-06)
CREATE UNIQUE INDEX uq_un_punto_abierto ON "punto_orden_dia" ("asamblea_id")
  WHERE estado = 'abierto';

ALTER TABLE "voto" ADD CONSTRAINT ck_voto_decision
  CHECK (decision IN ('a_favor', 'en_contra', 'abstencion'));

ALTER TABLE "resultado_votacion" ADD CONSTRAINT ck_resultado
  CHECK (resultado IN ('aprobado', 'rechazado'));
CREATE UNIQUE INDEX uq_resultado_punto ON "resultado_votacion" ("punto_id");

ALTER TABLE "acta" ADD CONSTRAINT ck_acta_estado
  CHECK (estado IN ('borrador', 'aprobada'));
CREATE UNIQUE INDEX uq_acta_asamblea ON "acta" ("asamblea_id");

ALTER TABLE "acta_aprobacion" ADD CONSTRAINT ck_acta_rol
  CHECK (rol_en_aprobacion IN ('presidente', 'secretario'));
CREATE UNIQUE INDEX uq_acta_aprobacion_rol ON "acta_aprobacion" ("acta_id", "rol_en_aprobacion");

-- Formulario público de registro de propietarios (RF-02)
ALTER TABLE "solicitud_censo" ADD CONSTRAINT ck_solicitud_estado
  CHECK (estado IN ('pendiente', 'aprobada', 'rechazada'));
-- Sin autorización de tratamiento de datos (Ley 1581 de 2012) no se guarda la solicitud
ALTER TABLE "solicitud_censo" ADD CONSTRAINT ck_solicitud_autoriza
  CHECK (autoriza_datos);
-- Una revisión siempre deja rastro de quién y cuándo; un rechazo, su motivo
ALTER TABLE "solicitud_censo" ADD CONSTRAINT ck_solicitud_revision
  CHECK (((estado = 'pendiente' AND revisado_por IS NULL AND fecha_revision IS NULL)
          OR (estado <> 'pendiente' AND revisado_por IS NOT NULL AND fecha_revision IS NOT NULL))
         AND (estado <> 'rechazada' OR motivo_rechazo IS NOT NULL));
-- Una sola solicitud pendiente por unidad: una unidad no recibe dos representantes en espera
CREATE UNIQUE INDEX uq_solicitud_pendiente ON "solicitud_censo" ("unidad_id")
  WHERE estado = 'pendiente';

