-- =====================================================================
-- INMUTABILIDAD (durabilidad del conteo y del acta)
-- =====================================================================

-- Votos y resultados no se pueden modificar ni borrar una vez escritos
CREATE OR REPLACE FUNCTION fn_bloquear_modificacion() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'La tabla % es inmutable: no se permite %', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_voto_inmutable
  BEFORE UPDATE OR DELETE ON "voto"
  FOR EACH ROW EXECUTE FUNCTION fn_bloquear_modificacion();

CREATE TRIGGER tg_resultado_inmutable
  BEFORE UPDATE OR DELETE ON "resultado_votacion"
  FOR EACH ROW EXECUTE FUNCTION fn_bloquear_modificacion();

-- No se aceptan votos sobre un punto que no esté abierto
CREATE OR REPLACE FUNCTION fn_validar_punto_abierto() RETURNS trigger AS $$
BEGIN
  IF (SELECT estado FROM punto_orden_dia WHERE id = NEW.punto_id) <> 'abierto' THEN
    RAISE EXCEPTION 'El punto % no está abierto a votación', NEW.punto_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_voto_punto_abierto
  BEFORE INSERT ON "voto"
  FOR EACH ROW EXECUTE FUNCTION fn_validar_punto_abierto();

-- Un acta aprobada no se puede editar ni borrar
CREATE OR REPLACE FUNCTION fn_acta_aprobada_inmutable() RETURNS trigger AS $$
BEGIN
  IF OLD.estado = 'aprobada' THEN
    RAISE EXCEPTION 'El acta % ya fue aprobada y es inmutable', OLD.id;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_acta_inmutable
  BEFORE UPDATE OR DELETE ON "acta"
  FOR EACH ROW EXECUTE FUNCTION fn_acta_aprobada_inmutable();
